/**
 * App-style icon tile: gradient square with a white duotone glyph.
 *
 * @param string $icon  Icon name.
 * @param string $color Palette key, or "brand" to follow the primary color.
 * @param int    $size  Glyph size.
 * @param string $class Extra class.
 * @return string
 */
function verdora_tile( $icon, $color = 'green', $size = 24, $class = '' ) {
	$palette = verdora_tile_palette();
	$style   = '';
	if ( isset( $palette[ $color ] ) ) {
		$style = sprintf( ' style="--q1:%s;--q2:%s"', esc_attr( $palette[ $color ][0] ), esc_attr( $palette[ $color ][1] ) );
	}
	return sprintf(
		'<span class="vd-tile %1$s"%2$s>%3$s</span>',
		esc_attr( trim( $class ) ),
		$style,
		verdora_icon( $icon, $size )
	);
}
